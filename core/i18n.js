export function normalizeLanguage(language) {
  return language === "uk" || language === "en" ? language : DEFAULT_LANGUAGE;
}

export function getStoredLanguage() {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;
  return normalizeLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY));
}

export function translate(language, key, params = {}) {
  const value = key.split(".").reduce(
    (current, segment) => current?.[segment],
    translations[normalizeLanguage(language)],
  );
  const fallback = key.split(".").reduce(
    (current, segment) => current?.[segment],
    translations[FALLBACK_LANGUAGE],
  );
  return String(value ?? fallback ?? key).replace(/\{(\w+)\}/g, (_, name) => (
    params[name] ?? `{${name}}`
  ));
}
